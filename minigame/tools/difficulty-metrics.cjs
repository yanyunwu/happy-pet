// Metric dictionary for the current game. Input knobs and observed outcomes are
// deliberately separate: correlated metrics must not be blindly summed.
const rows = [];
function group(category, items) {
  for (const item of items) {
    const [name, type, definition, effect, current, method, priority = 'P1'] = item;
    rows.push({
      id: 'D' + String(rows.length + 1).padStart(3, '0'),
      category,
      name,
      type,
      definition,
      effect,
      current,
      method,
      priority,
    });
  }
}
